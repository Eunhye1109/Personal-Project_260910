def write_doc(prs) -> Path:
    """발표본에 들어 있는 노트를 그대로 읽어 인쇄용 Word 문서로 낸다."""
    import docx
    from docx.shared import Pt, RGBColor

    doc = docx.Document()
    doc.styles["Normal"].font.name = "맑은 고딕"
    doc.styles["Normal"].font.size = Pt(10.5)

    p = doc.add_paragraph()
    r = p.add_run("발표 대본")
    r.font.size, r.font.bold = Pt(20), True
    r.font.color.rgb = RGBColor(0x1F, 0x38, 0x64)
    p = doc.add_paragraph()
    r = p.add_run("게임·영상물 등급분류 공공데이터 분석 · BI 분석가 과정 개인 프로젝트 · 최은혜")
    r.font.size = Pt(10)
    r.font.color.rgb = RGBColor(0x6B, 0x72, 0x80)

    for i, slide in enumerate(prs.slides, 1):
        title = ""
        for shape in slide.shapes:
            if not shape.has_text_frame or not shape.text_frame.text.strip():
                continue
            for para in shape.text_frame.paragraphs:
                for run in para.runs:
                    if run.font.size and run.font.size >= Pt(24):
                        title = shape.text_frame.text.strip().split(chr(10))[0]
                        break
                if title:
                    break
            if title:
                break
        p = doc.add_paragraph()
        p.paragraph_format.space_before = Pt(16)
        r = p.add_run(f"{i}. {title}")
        r.font.size, r.font.bold = Pt(13), True
        r.font.color.rgb = RGBColor(0x1F, 0x38, 0x64)
        body = (slide.notes_slide.notes_text_frame.text
                if slide.has_notes_slide and slide.notes_slide.notes_text_frame is not None
                else "")
        for line in (body or "(노트 없음)").split(chr(10)):
            q = doc.add_paragraph()
            q.paragraph_format.space_after = Pt(2)
            run = q.add_run(line)
            if line.startswith("["):
                run.font.bold = True
                run.font.color.rgb = RGBColor(0x59, 0x59, 0x59)

    out = ROOT / "docs" / "[BI 분석가 과정] 발표노트_260914_최은혜.docx"
    doc.save(out)
    return out


