def rebuild_with_breaks(para, new: str) -> bool:
    """수동 줄바꿈이 있는 문단. 첫 런의 서식을 그대로 물려 다시 조립한다."""
    runs = list(para.runs)
    if not runs:
        return False
    rPr = runs[0]._r.find(qn("a:rPr"))
    for child in list(para._p):
        if child.tag in (qn("a:r"), qn("a:br")):
            para._p.remove(child)
    for i, seg in enumerate(new.split(chr(11))):
        if i:
            br = para._p.makeelement(qn("a:br"), {})
            if rPr is not None:
                br.append(copy.deepcopy(rPr))
            para._p.append(br)
        r = para._p.makeelement(qn("a:r"), {})
        if rPr is not None:
            r.append(copy.deepcopy(rPr))
        t = para._p.makeelement(qn("a:t"), {})
        t.text = seg
        r.append(t)
        para._p.append(r)
    return True


def set_text(para, new: str) -> bool:
    """서식을 유지한 채 문단의 글자만 바꾼다. 공통 앞부분의 런은 손대지 않는다."""
    if chr(11) in new:
        return rebuild_with_breaks(para, new)
    runs = list(para.runs)
    if not runs:
        return False
    old = "".join(r.text for r in runs)
    i = 0
    while i < min(len(old), len(new)) and old[i] == new[i]:
        i += 1
    keep, acc = 0, 0
    for r in runs:
        if acc + len(r.text) <= i and keep < len(runs) - 1:
            acc += len(r.text)
            keep += 1
        else:
            break
    runs[keep].text = new[acc:]
    for r in runs[keep + 1:]:
        r._r.getparent().remove(r._r)
    return True


def frames(shape):
    if shape.has_text_frame:
        yield shape.text_frame
    elif shape.has_table:
        for row in shape.table.rows:
            for cell in row.cells:
                yield cell.text_frame


